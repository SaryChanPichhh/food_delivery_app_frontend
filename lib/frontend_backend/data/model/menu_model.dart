class MenuModel {
  final String? id;
  final String? name;
  final String? description;
  final String? image;
  final String? price;
  final String? cateId;
  final String? resId;

  MenuModel({
    required this.id,
    required this.name,
    required this.description,
    required this.image,
    required this.price,
    required this.cateId,
    required this.resId,
  });
}
